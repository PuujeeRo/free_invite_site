// Widen every leaf to `string`: both locales must share one Dictionary shape,
// but their actual text values are naturally different literals, which an
// `as const` dictionaries object would otherwise bake in as mismatched types.
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };
export type Dictionary = Widen<(typeof dictionaries)["en"]>;

export function getDictionary(locale: Locale): Dictionary {
  return dictionaries[locale];
}
