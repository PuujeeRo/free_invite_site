/**
 * Installs Naashir into its own schema of a Supabase project that another app
 * already uses, instead of into `public`.
 *
 *   npx tsx scripts/hosted-schema.ts build            # write supabase/hosted/naashir/*.sql
 *   npx tsx scripts/hosted-schema.ts check            # fail if those files are out of date
 *   npx tsx scripts/hosted-schema.ts apply            # uses DATABASE_POOL_URL from .env.local
 *   npx tsx scripts/hosted-schema.ts apply --from=0007
 *   npx tsx scripts/hosted-schema.ts apply "<connection string>"
 *
 * supabase/migrations/ stays the single source: it installs into `public`,
 * which is what a project of its own, local dev and the test database use.
 * The files under supabase/hosted/ are those same migrations rewritten for
 * another schema, between a setup file and a finish file, so they are
 * generated and never edited by hand. Add a migration, then run `build`.
 *
 * `apply` runs them in order against a database, one file per transaction, and
 * stops at the first error. It has to connect as `postgres` (the Session
 * pooler string from the Supabase dashboard): two migrations touch Supabase's
 * own `auth` and `storage` schemas, which no other role may change. The same
 * files can instead be pasted into the SQL Editor one at a time, in order.
 *
 * The app is pointed at the schema with NEXT_PUBLIC_SUPABASE_DB_SCHEMA, and
 * the schema has to be added to the project's exposed schemas (Project
 * Settings -> API), or the Data API refuses every request for it.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Client } from "pg";

const ROOT = process.cwd();
const MIGRATIONS = join(ROOT, "supabase/migrations");
const SCHEMA_NAME = /^[a-z_][a-z0-9_]*$/;
export const DEFAULT_SCHEMA = "naashir";

export interface HostedFile {
  name: string;
  sql: string;
}

function header(schema: string, source: string): string {
  return [
    `-- GENERATED by scripts/hosted-schema.ts from ${source}. Do not edit:`,
    `-- change the source and run "npx tsx scripts/hosted-schema.ts build".`,
    `--`,
    `-- Run as postgres, in number order, one file at a time.`,
    ``,
    // Not `public`: a name missing from this schema must fail, not quietly
    // pick up the other app's object of the same name. `extensions` is where
    // Supabase keeps pgcrypto.
    `set search_path = ${schema}, extensions;`,
    ``,
    ``,
  ].join("\n");
}

/** One migration, rewritten to install into `schema` instead of `public`. */
export function rewriteMigration(sql: string, schema: string): string {
  const out = sql
    // Schema-qualified names only. "from public, anon" in a REVOKE is the
    // PUBLIC pseudo-role and has no dot, so it is left alone.
    .replace(/\bpublic\.(?=[a-z_"])/g, `${schema}.`)
    .replace(/search_path\s*=\s*public\b/g, `search_path = ${schema}`)
    // Triggers on auth.users share one namespace across every app in the
    // project, and this is the name Supabase's own tutorials use.
    .replace(/\bon_auth_user_created\b/g, `${schema}_on_auth_user_created`);
  if (/\bpublic\./.test(out)) throw new Error("a public.<name> reference survived the rewrite");
  return out;
}

function setupSql(schema: string): string {
  return `${header(schema, "its own template")}-- Refuses to run twice or into the wrong place: every file after this one
-- assumes an existing, empty schema.
do $$
begin
  if not exists (select 1 from pg_namespace where nspname = '${schema}') then
    raise exception 'schema "${schema}" does not exist -- create it first (docs/supabase-naashir-user.md)';
  end if;
  if exists (
    select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = '${schema}' and c.relkind in ('r', 'v', 'S')
  ) or exists (
    select 1 from pg_type t join pg_namespace n on n.oid = t.typnamespace
     where n.nspname = '${schema}' and t.typtype = 'e'
  ) then
    raise exception 'schema "${schema}" is not empty -- this installer is for a first install only';
  end if;
  if exists (
    select 1 from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'auth' and c.relname = 'users' and t.tgname = '${schema}_on_auth_user_created'
  ) then
    raise exception 'trigger ${schema}_on_auth_user_created already exists on auth.users';
  end if;
end
$$;

-- What Supabase does for \`public\` by itself and for no other schema: let its
-- API roles reach the schema and everything created in it from now on. This
-- only makes a query possible to attempt; row-level security, enabled on every
-- table by the migrations, still decides which rows it sees.
grant usage on schema ${schema} to anon, authenticated, service_role;
alter default privileges in schema ${schema} grant all on tables to anon, authenticated, service_role;
alter default privileges in schema ${schema} grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema ${schema} grant all on routines to anon, authenticated, service_role;
`;
}

function finishSql(schema: string): string {
  return `${header(schema, "its own template")}-- 1. The sign-up trigger must never be the reason a sign-up fails.
-- auth.users is shared with the other app in this project, and this trigger
-- runs for its new users too: an error here would stop people registering
-- THERE. So a failed insert is reported as a warning and the sign-up goes on.
create or replace function ${schema}.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ${schema}
as $$
begin
  begin
    insert into ${schema}.profiles (id, email) values (new.id, new.email)
    on conflict (id) do nothing;
  exception when others then
    raise warning '${schema}.handle_new_user: no profile created for % (%)', new.id, sqlerrm;
  end;
  return new;
end;
$$;

-- 2. People who registered before today have no row yet, and the trigger only
-- fires for new ones. Without a profile they could sign in but not create an
-- invitation.
insert into ${schema}.profiles (id, email)
select id, email from auth.users
on conflict (id) do nothing;

-- 3. The schema's own login role, when it exists, can read and maintain the
-- tables (they are owned by postgres, which created them).
do $$
begin
  if exists (select 1 from pg_roles where rolname = '${schema}_admin') then
    execute 'grant all on all tables in schema ${schema} to ${schema}_admin';
    execute 'grant all on all sequences in schema ${schema} to ${schema}_admin';
    execute 'grant all on all routines in schema ${schema} to ${schema}_admin';
    execute 'alter default privileges in schema ${schema} grant all on tables to ${schema}_admin';
    execute 'alter default privileges in schema ${schema} grant all on sequences to ${schema}_admin';
    execute 'alter default privileges in schema ${schema} grant all on routines to ${schema}_admin';
  end if;
end
$$;

-- 4. Have the Data API pick up the new tables. It still serves them only once
-- "${schema}" is listed under Project Settings -> API -> Exposed schemas.
notify pgrst, 'reload schema';
`;
}

/** Every file of the install, in the order it must run. */
export function buildFiles(schema: string): HostedFile[] {
  if (!SCHEMA_NAME.test(schema) || schema === "public") throw new Error(`"${schema}" is not a usable schema name`);
  const migrations = readdirSync(MIGRATIONS)
    .filter((f) => f.endsWith(".sql"))
    .sort();
  return [
    { name: "0000_setup.sql", sql: setupSql(schema) },
    ...migrations.map((file) => ({
      name: file,
      sql:
        header(schema, `supabase/migrations/${file}`) +
        rewriteMigration(readFileSync(join(MIGRATIONS, file), "utf8").replace(/\r\n/g, "\n"), schema),
    })),
    { name: "9000_finish.sql", sql: finishSql(schema) },
  ];
}


/** Reads NAME=value from .env.local. */
function envValue(name: string): string | undefined {
  const file = join(ROOT, ".env.local");
  if (!existsSync(file)) return undefined;
  for (const raw of readFileSync(file, "utf8").split("\n")) {
    const line = raw.trim();
    if (!line.startsWith(name)) continue;
    const rest = line.slice(name.length).trimStart();
    if (!rest.startsWith("=")) continue;
    const value = rest.slice(1).trim().replace(/^["']/, "").replace(/["']$/, "");
    return value || undefined;
  }
  return undefined;
}

function outDir(schema: string): string {
  return join(ROOT, "supabase/hosted", schema);
}

/** Runs the install. Each file is one implicit transaction, so a failure leaves whole files applied or not. */
export async function applyFiles(client: Client, files: HostedFile[], log: (line: string) => void): Promise<void> {
  for (const file of files) {
    try {
      await client.query(file.sql);
      log(`applied  ${file.name}`);
    } catch (err) {
      log(`FAILED   ${file.name}: ${(err as Error).message}`);
      throw new Error(`stopped at ${file.name}; nothing after it was run`);
    }
  }
}

async function main() {
  const [command, ...rest] = process.argv.slice(2);
  const flags = rest.filter((a) => a.startsWith("--"));
  const args = rest.filter((a) => !a.startsWith("--"));
  const schema = flags.find((f) => f.startsWith("--schema="))?.slice("--schema=".length) ?? DEFAULT_SCHEMA;
  const files = buildFiles(schema);

  if (command === "build") {
    rmSync(outDir(schema), { recursive: true, force: true });
    mkdirSync(outDir(schema), { recursive: true });
    for (const file of files) writeFileSync(join(outDir(schema), file.name), file.sql);
    console.log(`wrote ${files.length} files to supabase/hosted/${schema}/`);
    return;
  }

  if (command === "check") {
    const stale = files.filter((file) => {
      const path = join(outDir(schema), file.name);
      return !existsSync(path) || readFileSync(path, "utf8").replace(/\r\n/g, "\n") !== file.sql;
    });
    const extra = existsSync(outDir(schema))
      ? readdirSync(outDir(schema)).filter((f) => !files.some((file) => file.name === f))
      : [];
    if (stale.length === 0 && extra.length === 0) {
      console.log(`supabase/hosted/${schema}/ is up to date (${files.length} files)`);
      return;
    }
    console.error(`supabase/hosted/${schema}/ is out of date: ${[...stale.map((f) => f.name), ...extra].join(", ")}`);
    console.error(`run: npx tsx scripts/hosted-schema.ts build`);
    process.exit(1);
  }

  if (command === "apply") {
    const connectionString = args[0] ?? envValue("DATABASE_POOL_URL");
    if (!connectionString) {
      throw new Error("apply needs DATABASE_POOL_URL in .env.local, or a connection string (the Session pooler one, as postgres)");
    }
    const from = flags.find((f) => f.startsWith("--from="))?.slice("--from=".length);
    const todo = from ? files.filter((f) => f.name.slice(0, 4) >= from) : files;
    if (todo.length === 0) throw new Error(`no file at or after ${from}`);

    const client = new Client({ connectionString, connectionTimeoutMillis: 10000 });
    await client.connect();
    try {
      const who = await client.query<{ db: string; usr: string }>(`select current_database() as db, current_user as usr`);
      console.log(`database ${who.rows[0].db} as ${who.rows[0].usr}, schema ${schema}\n`);
      await applyFiles(client, todo, console.log);
      console.log(`\nInstalled. Now add "${schema}" to the exposed schemas in the Supabase dashboard.`);
    } finally {
      await client.end();
    }
    return;
  }

  throw new Error(`usage: hosted-schema.ts build | check | apply "<connection string>" [--from=NNNN] [--schema=name]`);
}

// Only when run directly: scripts/verify-hosted-schema.ts imports the functions above.
if (process.argv[1]?.replace(/\\/g, "/").endsWith("scripts/hosted-schema.ts")) {
  main().catch((err) => {
    // A connection string must never reach the terminal or a log.
    console.error("FAILED:", (err as Error).message.replace(/postgres(ql)?:\/\/\S+/g, "<connection string>"));
    process.exit(1);
  });
}
